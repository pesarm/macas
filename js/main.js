/* ── Language ──────────────────────────────────────────────── */
function detectLang() {
  const saved = localStorage.getItem('lang');
  if (saved && t[saved]) return saved;
  const nav = (navigator.language || 'en').toLowerCase().slice(0, 2);
  return t[nav] ? nav : 'en';
}

function applyLang(lang) {
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
  const strings = t[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (strings[key] !== undefined) el.textContent = strings[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (strings[key] !== undefined) el.placeholder = strings[key];
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Update WhatsApp message text
  const waBtn = document.getElementById('whatsapp-btn');
  if (waBtn) {
    const msgs = {
      en: "Hi! I'm interested in booking the villa.",
      pt: 'Olá! Estou interessado/a em reservar a villa.',
      es: '¡Hola! Me interesa reservar la villa.',
    };
    const base = waBtn.href.split('?')[0];
    waBtn.href = `${base}?text=${encodeURIComponent(msgs[lang] || msgs.en)}`;
  }
}


/* ── Scroll reveal ─────────────────────────────────────────── */
const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

/* ── Gallery lightbox ──────────────────────────────────────── */
let currentIdx = 0;
const galleryImgs = Array.from(document.querySelectorAll('.gallery-item img'));

function openLightbox(idx) {
  const img = galleryImgs[idx];
  if (!img || !img.naturalWidth) return; // no photo loaded
  currentIdx = idx;
  const lb = document.getElementById('lightbox');
  lb.classList.remove('hidden');
  lb.classList.add('open');
  updateLightbox();
  document.body.style.overflow = 'hidden';
}

function closeLightbox() {
  const lb = document.getElementById('lightbox');
  lb.classList.add('hidden');
  lb.classList.remove('open');
  document.body.style.overflow = '';
}

function updateLightbox() {
  const img = galleryImgs[currentIdx];
  document.getElementById('lb-img').src = img ? img.src : '';
  document.getElementById('lb-img').alt = img ? img.alt : '';
  document.getElementById('lb-counter').textContent = `${currentIdx + 1} / ${galleryImgs.length}`;
}

function prevPhoto() {
  currentIdx = (currentIdx - 1 + galleryImgs.length) % galleryImgs.length;
  updateLightbox();
}
function nextPhoto() {
  currentIdx = (currentIdx + 1) % galleryImgs.length;
  updateLightbox();
}

document.getElementById('lightbox').addEventListener('click', e => {
  if (e.target === e.currentTarget) closeLightbox();
});

document.addEventListener('keydown', e => {
  if (document.getElementById('lightbox').classList.contains('open')) {
    if (e.key === 'Escape') closeLightbox();
    if (e.key === 'ArrowLeft') prevPhoto();
    if (e.key === 'ArrowRight') nextPhoto();
  }
});

/* ── Gallery placeholder visibility ───────────────────────── */
function checkGalleryPhotos() {
  let missingAll = true;
  galleryImgs.forEach(img => {
    img.addEventListener('load', () => {
      img.nextElementSibling && (img.nextElementSibling.style.opacity = '0');
      missingAll = false;
    });
    img.addEventListener('error', () => {
      img.style.display = 'none';
    });
    if (img.complete && img.naturalWidth > 0) missingAll = false;
  });
  const note = document.getElementById('photos-note');
  if (note && missingAll) setTimeout(() => { note.style.display = 'block'; }, 500);
}

/* ── Contact form (Netlify) ────────────────────────────────── */
const form = document.getElementById('contact-form');
if (form) {
  form.addEventListener('submit', async e => {
    e.preventDefault();
    const btn = form.querySelector('[type="submit"]');
    const origText = btn.textContent;
    btn.textContent = '…';
    btn.disabled = true;

    try {
      const res = await fetch('/', {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: new URLSearchParams(new FormData(form)).toString(),
      });
      if (res.ok) {
        form.reset();
        document.getElementById('form-success').classList.remove('hidden');
        form.style.opacity = '0.4';
        form.style.pointerEvents = 'none';
      } else {
        throw new Error('Network error');
      }
    } catch {
      btn.textContent = origText;
      btn.disabled = false;
      alert('Something went wrong. Please try WhatsApp or email instead.');
    }
  });
}

